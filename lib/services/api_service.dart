  // Aliases for compatibility
  static Future<void> submitTeamStats({
    required dynamic matchId,
    required dynamic teamId,
    required int goals,
    required int passes,
    required int fouls,
    required int corners,
  }) => submitTeamMatchStats(
        matchId: matchId,
        teamId: teamId,
        goals: goals,
        passes: passes,
        fouls: fouls,
        corners: corners,
      );

  static Future<void> submitPlayerStats({
    required dynamic matchId,
    required dynamic playerId,
    required int goals,
    required int assists,
    required int yellowCard,
    required int redCard,
    required double topSpeed,
    required double totalDistance,
