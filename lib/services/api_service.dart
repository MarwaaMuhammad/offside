        goals: goals,
        assists: assists,
        yellowCard: yellowCard,
        redCard: redCard,
        topSpeed: topSpeed,
        totalDistance: totalDistance,
      );

  // ═══════════════════════════════════════════════════════════════
  //  PROFILE & MEDIA
  // ═══════════════════════════════════════════════════════════════

  static Future<void> updateUserProfile({
    required String email,
    required String role,
    required Map<String, dynamic> updates,
  }) async {
    final table = role == 'player' ? 'PLAYERS' : 'USERS';
    _handleResponse(
      await http.patch(
        _uri(table, {'email': 'eq.$email'}),
        headers: _authHeaders,
        body: jsonEncode(updates),
      ),
    );
  }

  static Future<String?> uploadProfileImage(File file, String userId) async {
    try {
      final fileName = 'avatar_${userId}_${DateTime.now().millisecondsSinceEpoch}.png';
      await Supabase.instance.client.storage.from('avatars').upload(fileName, file);
      return Supabase.instance.client.storage.from('avatars').getPublicUrl(fileName);
    } catch (e) {
      debugPrint("❌ [ApiService] Upload Error: $e");
      return null;
    }
  }

  static Future<Map<String, dynamic>> sendInvitation({
    required String teamName,
    required String leagueName,
    required String playerName,
    required String playerId,
    required int jerseyNumber,
  }) async {
    return _handleResponse(
      await http.post(
        _uri('INVITATIONS'),
        headers: _authHeaders,
        body: jsonEncode({
          'team_name': teamName,
          'league_name': leagueName,
          'player_name': playerName,
          'player_id': playerId,
          'jersey_number': jerseyNumber,
          'status': 'pending',
          'timestamp': DateTime.now().toIso8601String(),
        }),
      ),
    );
  }

  static Future<void> updateInvitationStatus(String inviteId, String status) async {
    _handleResponse(
      await http.patch(
        _uri('INVITATIONS', {'invitation_id': 'eq.$inviteId'}),
        headers: _authHeaders,
        body: jsonEncode({'status': status}),
      ),
    );
  }

  static Future<bool> ping() async {
    try {
      return (await http.get(_uri('PLAYERS'), headers: _authHeaders).timeout(const Duration(seconds: 5))).statusCode == 200;
    } catch (_) {
      return false;
    }
  }
}

class ApiException implements Exception {
  final int statusCode;
  final String message;
  final String? url;

  ApiException({required this.statusCode, required this.message, this.url});

  @override
  String toString() => 'ApiException [$statusCode]${url != null ? ' at $url' : ''}: $message';
}
