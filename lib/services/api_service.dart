        _uri('PLAYER_MATCH_STATS'),
        headers: _authHeaders,
        body: jsonEncode({
          'match_id': matchId,
          'player_id': playerId,
          'goals': goals,
          'assists': assists,
          'yellow_card': yellowCard,
          'red_card': redCard,
          'top_speed': topSpeed,
          'total_distance': totalDistance,
